# Offline end-to-end tests for the opendkim service handler: dkim key
# generation (openssl handler), domain mapping via the mock domain
# handler and KeyTable/SigningTable generation. The opendkim daemon
# itself is not needed - the reload step fails gracefully in the test
# env (no systemd unit opendkim), the generated tables are asserted on
# disk against the generated key and the published DNS selector.

import unittest
import os
import re
import shutil
import base64
from cryptography.hazmat.primitives import serialization
from test.test_config import testdomain
from cryptdomainmgr.modules.common.cdmprochelper import runCmd

tmpdirOpendkim = "/tmp/test_cryptdomainmgr_opendkim"


class TestServiceHandlerOpendkim(unittest.TestCase):

    def setUp(self):
        shutil.rmtree(tmpdirOpendkim, ignore_errors=True)

    def mkConfig(self, domainEntries):
        return '\n'.join([
            "[cdm]", "statedir=" + tmpdirOpendkim,
            "[domain]", "handler=mock", "mockstore=" + tmpdirOpendkim + "/mockdns.json",
            "[domain:" + testdomain + "]"] + domainEntries + [
            "[dkim]", "handler=openssl", "keysize=2048",
            "[dkim:mydkim]", "keybasename=key", "keyname=dkimfile.key",
            "keylocation=" + tmpdirOpendkim + "/dkim",
            "signingconfdestinationfile=" + tmpdirOpendkim + "/etc/rspamd/local.d/dkim_signing.conf",
            "[service:opendkim]", "handler=opendkim", "dkim=mydkim", "reload=false",
            "keytablefile=" + tmpdirOpendkim + "/etc/opendkim/KeyTable",
            "signingtablefile=" + tmpdirOpendkim + "/etc/opendkim/SigningTable"])

    def testOpendkimTables(self):
        conf = self.mkConfig(["dkim.mydkim=auto"])
        stdout = runCmd("python3 -m cryptdomainmgr --prepare --config-content '{}' 2>&1".format(conf))
        runCmd("python3 -m cryptdomainmgr --rollover --config-content '{}' 2>&1".format(conf))

        keytableFile = os.path.join(tmpdirOpendkim, "etc", "opendkim", "KeyTable")
        signingtableFile = os.path.join(tmpdirOpendkim, "etc", "opendkim", "SigningTable")
        with self.subTest("check KeyTable written"):
            self.assertTrue(os.path.isfile(keytableFile))
        with self.subTest("check SigningTable written"):
            self.assertTrue(os.path.isfile(signingtableFile))

        # the selector is generated by the dkim prepare phase and appears
        # both in the published DNS record and in the tables
        selectorMatch = re.search(r"add \(new\) DKIM for (key_\d+)\._domainkey\.", stdout)
        with self.subTest("check DNS record published with timestamped selector"):
            self.assertIsNotNone(selectorMatch)
        selector = selectorMatch.group(1)

        with open(os.path.join(tmpdirOpendkim, "dkim", "dkimfile.key"), 'rb') as f:
            key = serialization.load_pem_private_key(f.read(), password=None)
        expectedP = base64.b64encode(key.public_key().public_bytes(
            serialization.Encoding.DER,
            serialization.PublicFormat.SubjectPublicKeyInfo)).decode()

        with open(keytableFile) as f:
            keytable = f.read()
        with self.subTest("check KeyTable entry format and selector"):
            self.assertRegex(keytable, r"^{}._domainkey\.{} {}:{}".format(re.escape(selector), re.escape(testdomain), re.escape(testdomain), re.escape(selector)))
        with self.subTest("check KeyTable references deployed key file"):
            self.assertIn(os.path.join(tmpdirOpendkim, "dkim", "dkimfile.key"), keytable)

        with open(signingtableFile) as f:
            signingtable = f.read()
        with self.subTest("check SigningTable entry format"):
            self.assertRegex(signingtable, r"^\*@{} {}._domainkey\.{}".format(re.escape(testdomain), re.escape(selector), re.escape(testdomain)))
